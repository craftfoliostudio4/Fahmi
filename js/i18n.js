function translateDOM(lang) {

  // Handle placeholders in forms
  const inputs = document.querySelectorAll('input[placeholder], textarea[placeholder]');
  inputs.forEach(input => {
    if (!input.originalPlaceholder) {
      input.originalPlaceholder = input.placeholder;
    }
    const orig = input.originalPlaceholder;
    if (lang === 'ar' && dictionary[orig]) {
      input.placeholder = dictionary[orig];
    } else if (lang === 'en') {
      input.placeholder = orig;
    }
  });

  // Handle select options
  const options = document.querySelectorAll('option');
  options.forEach(opt => {
    if (!opt.originalText) {
      opt.originalText = opt.textContent;
    }
    const orig = opt.originalText;
    if (lang === 'ar' && dictionary[orig]) {
      opt.textContent = dictionary[orig];
    } else if (lang === 'en') {
      opt.textContent = orig;
    }
  });
}
